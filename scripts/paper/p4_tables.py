#!/usr/bin/env python3
"""Build Table 2 and Table 3 as markdown from results files.

Stage 4 of the paper-prep task. Both tables are generated rather than typed so
that every cell traces to a file. Table 1 lists data-source provenance and is
maintained by hand in docs/paper/tables/Table1_data_sources.md, because its
contents are dates and version strings recorded in documents, not computed
values.

Table 2  four-tool benchmark on n=254: AUC and average precision with
         bootstrap CI, plus the DeLong comparison against AlphaMissense.
S1 Table  the concordant set (was Table 3 before 2026-10-27), with gene-mask and centre-mask membership.

Reads : results/paper/auc_ci.csv
        results/phase1/delong_tests_dedup.csv
        results/paper/concordant_set.csv
Writes: docs/paper/tables/Table2_four_tool_benchmark.md
        docs/paper/tables/S1_Table_concordant_set.md

Usage:
    python scripts/paper/p4_tables.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / "docs" / "paper" / "tables"

MISSING = "[NOT IN REPO]"


def md_table(header: list[str], rows: list[list[str]]) -> str:
    """Render a markdown table from a header and a list of row values."""
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def build_table2() -> None:
    """Write Table 2: the four-tool benchmark with CIs and DeLong tests."""
    ci = pd.read_csv(ROOT / "results/paper/auc_ci.csv")
    ci = ci[ci["cohort"] == "four_tool_dedup"].set_index("tool")
    dl = pd.read_csv(ROOT / "results/phase1/delong_tests_dedup.csv")
    dl_map = {r["tool_b"]: r for _, r in dl.iterrows()}
    # delong_tests_dedup.csv names PolyPhen; the paper uses PolyPhen-2.
    alias = {"AlphaMissense": None, "PolyPhen-2": "PolyPhen", "CADD": "CADD", "SIFT": "SIFT"}

    rows: list[list[str]] = []
    for tool in ["AlphaMissense", "PolyPhen-2", "CADD", "SIFT"]:
        r = ci.loc[tool]
        key = alias[tool]
        if key is None:
            delong = "reference"
        else:
            d = dl_map[key]
            p = float(d["p"])
            # The file stores p = 0.0 where the DeLong p-value underflows.
            p_txt = "p < 0.0001" if p == 0 else f"p = {p:.6f}".rstrip("0")
            delong = f"Z = {float(d['z']):.4f}, {p_txt}"
        rows.append([
            tool,
            f"{r['auc']:.4f} ({r['auc_ci_lo']:.4f}–{r['auc_ci_hi']:.4f})",
            f"{r['ap']:.4f} ({r['ap_ci_lo']:.4f}–{r['ap_ci_hi']:.4f})",
            delong,
        ])

    n = int(ci.iloc[0]["n"])
    n_pos = int(ci.iloc[0]["n_pos"])
    n_neg = int(ci.iloc[0]["n_neg"])

    body = f"""# Table 2. Four-tool benchmark on CFTR2-labelled missense variants

Discrimination of four missense pathogenicity predictors against CFTR2 binary
labels on the {n} deduplicated variants carrying all four scores
({n_pos} CF-causing, {n_neg} Non CF-causing). Confidence intervals are
percentile bootstrap, 2,000 resamples, seed 42. The DeLong column compares each
tool's ROC curve against AlphaMissense on the same variants.

{md_table(
    ["Tool", "AUC (95% CI)", "Average precision (95% CI)", "DeLong vs AlphaMissense"],
    rows,
)}

**Cell sources.** AUC, average precision and both intervals:
`results/paper/auc_ci.csv`, rows with `cohort == four_tool_dedup`, columns
`auc`, `auc_ci_lo`, `auc_ci_hi`, `ap`, `ap_ci_lo`, `ap_ci_hi`. Point estimates
reproduce `results/phase1/benchmark_metrics_dedup.csv` columns `auc` and `ap`.
DeLong Z and p: `results/phase1/delong_tests_dedup.csv`, columns `z` and `p`.
Cohort sizes: `results/phase1/benchmark_metrics_dedup.csv`, columns `n`,
`n_pos`, `n_neg`.

**Notes.** The DeLong implementation is the fast algorithm of Sun and Xu
(2014), recorded in the `implementation` column of
`results/phase1/delong_tests_dedup.csv` and coded in
`scripts/phase1_utils_delong.py`. SIFT is scored as 1 minus the SIFT score so
that higher means more damaging in every column
(`results/phase1/benchmark_cohort_dedup.csv`, column `sift_score_inv`).
The AUC confidence intervals of all four tools are wide because there are only
{n_neg} negatives; the DeLong test is paired and is the comparison that carries
weight, not the overlap between intervals.

Generated by `scripts/paper/p4_tables.py`.
"""
    (TABLES / "Table2_four_tool_benchmark.md").write_text(body)
    print(body)


def build_table3() -> None:
    """Write S1 Table: the concordant set with GM and CM membership marked."""
    df = pd.read_csv(ROOT / "results/paper/concordant_set.csv")

    header = [
        "Protein change", "Position (hg38)", "Domain", "Exon / intron",
        "Distance to splice site (bp)", "AlphaMissense", "AlphaGenome SPLICE raw",
        "AlphaGenome SPLICE quantile", "SpliceAI delta", "SpliceAI type",
        "gnomAD v4 max AF", "CFTR2 status", "In minigene benchmark", "GM", "CM",
    ]
    rows: list[list[str]] = []
    for _, r in df.iterrows():
        # The column mixes numbers with the string "absent from gnomAD v4".
        af = r["gnomad_v4_max_af"]
        try:
            af_txt = f"{float(af):.2e}"
        except (TypeError, ValueError):
            af_txt = str(af)
        rows.append([
            str(r["protein_change"]),
            f"{int(r['pos_hg38']):,} {r['ref']}>{r['alt']}",
            str(r["cftr_domain"]),
            str(r["exon_or_intron"]),
            str(r["distance_to_nearest_splice_site_bp"]),
            f"{float(r['alphamissense_score']):.4f}",
            f"{float(r['ag_splice_raw']):.4f}",
            f"{float(r['ag_splice_quantile']):.6f}",
            f"{float(r['spliceai_max_delta']):.2f}",
            str(r["spliceai_type"]),
            af_txt,
            str(r["cftr2_status"]),
            str(r["in_experimental_benchmark"]),
            "yes" if r["in_GM"] == "yes" else "–",
            "yes" if r["in_CM"] == "yes" else "–",
        ])

    n_gm = int((df["in_GM"] == "yes").sum())
    n_cm = int((df["in_CM"] == "yes").sum())

    body = f"""# S1 Table. The concordant set

Variants flagged by both AlphaGenome and SpliceAI among the 1,278
AlphaMissense-ambiguous CFTR missense SNVs. Two definitions are reported.
GM: AlphaGenome gene-mask SPLICE quantile > 0.95 and SpliceAI maximum delta
> 0.5 (n = {n_gm}). CM: AlphaGenome centre-mask splice score in the top 5% of
the 1,278 and SpliceAI maximum delta > 0.5 (n = {n_cm}). The CM set is a subset
of the GM set, so the union is {len(df)} variants. Rows are ordered by genomic
position.

{md_table(header, rows)}

**Cell sources.** Protein change, position, reference and alternate allele,
AlphaGenome SPLICE raw and quantile: `results/alphagenome/alphagenome_full_cftr_results.csv`.
Centre-mask splice score: `results/alphagenome/rescore_centermask.csv`, column
`cm_splice_501`. SpliceAI delta and the four channel scores:
`results/comparator_scores.csv`, columns `SpliceAI_max_delta`,
`SpliceAI_DS_AG`, `SpliceAI_DS_AL`, `SpliceAI_DS_DG`, `SpliceAI_DS_DL`.
AlphaMissense score: `results/alphagenome/alphagenome_full_cftr_results.csv`,
column `am_pathogenicity`. gnomAD v4 maximum allele frequency:
`results/gnomad_cftr_lookup.csv`, column `gnomad_max_af`; "absent from gnomAD v4"
means the lookup returned no record. CFTR2 status:
`data/cftr2_results_annotated.csv`, column `determination_2026`, matched on
`am_variant`. Minigene membership: `results/experimental_benchmark.csv`,
column `minigene_result`. Domain: residue number against the CFTR domain
boundaries used in `scripts/alphamissense_analysis.py` line 146.
Full table with every column: `results/paper/concordant_set.csv`.

**{MISSING} columns.** Exon or intron and distance to the nearest splice site
cannot be filled: the repository holds no CFTR exon-boundary annotation, no GTF
and no BED file, and no script computes either quantity for this cohort. The
`dist_bp` column of `results/experimental_benchmark.csv` covers only the 23
minigene variants and has no generating script.

Generated by `scripts/paper/p4_tables.py`.
"""
    (TABLES / "S1_Table_concordant_set.md").write_text(body)
    print(body)


def main() -> None:
    """Write Tables 2 and 3."""
    TABLES.mkdir(parents=True, exist_ok=True)
    build_table2()
    build_table3()
    print(f"wrote tables under {TABLES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
